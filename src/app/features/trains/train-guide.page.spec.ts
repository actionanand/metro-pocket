import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { TrainGuidePage } from './train-guide.page';
import { AppPlatformService } from '../../core/platform/app-platform.service';
import { TrainCsvService } from '../../core/trains/train-csv.service';
import { LocalFileService } from '../../core/trains/local-file.service';
import { parseTrainCsv, trainCsvTemplate } from '../../core/trains/train-csv';
import { textFile } from '../../core/trains/train-test-fixtures';

describe('Bundled Web Train CSV Guide', () => {
  const files = { download: vi.fn() };
  let web = true;
  beforeEach(async () => {
    vi.clearAllMocks();
    web = true;
    await TestBed.configureTestingModule({
      imports: [TrainGuidePage],
      providers: [
        provideRouter([]),
        { provide: LocalFileService, useValue: files },
        { provide: AppPlatformService, useValue: { isWeb: () => web, isAndroid: () => !web } },
      ],
    }).compileComponents();
  });
  it('contains the full local guide and fictional sample generated by the shared template', () => {
    const fixture = TestBed.createComponent(TrainGuidePage);
    fixture.detectChanges();
    expect(fixture.nativeElement.textContent).toContain('Train CSV Guide');
    expect(fixture.nativeElement.textContent).toContain('Daily');
    expect(fixture.nativeElement.textContent).toContain('whole-day gaps');
    expect(fixture.nativeElement.textContent).toContain('Replace Schedule');
    expect(fixture.componentInstance.sample).toBe(trainCsvTemplate());
    expect(parseTrainCsv(fixture.componentInstance.sample).runningDays).toHaveLength(7);
    fixture.componentInstance.downloadTemplate();
    expect(files.download).toHaveBeenCalledWith(
      trainCsvTemplate(),
      'metropocket-train-template.csv',
      expect.stringContaining('text/csv'),
    );
  });
  it('the shared CSV service rejects Android prepare/template calls before reading files', async () => {
    web = false;
    const csv = TestBed.inject(TrainCsvService);
    const file = textFile(trainCsvTemplate());
    const read = vi.spyOn(file, 'text');
    await expect(csv.prepare(file)).rejects.toThrow('only on Web/PWA');
    expect(() => csv.downloadTemplate()).toThrow('only on Web/PWA');
    expect(read).not.toHaveBeenCalled();
    expect(files.download).not.toHaveBeenCalled();
  });
});
